#include <stdio.h>

// Функция pulse() по-прежнему выводит ровно один символ '@'
void pulse() {
    printf("@");
}

int main() {
    int current_line = 1; // Номер текущей строки (и количество символов в ней)
    int total_chars = 0;  // Счётчик выведенных символов
    
    // Цикл работает, пока мы не выведем ровно 10 символов
    while (total_chars < 10) {
        
        // Внутренний цикл печатает нужное количество символов для текущей строки
        for (int i = 0; i < current_line; i++) {
            pulse();
            total_chars++; // Считаем каждый напечатанный символ
            
            // Если вывели ровно 10 символов, прерываем печать
            if (total_chars == 10) {
                break;
            }
        }
        
        // Перенос строки формируется только в main() после окончания текущего ряда
        printf("\n");
        
        // Переходим к следующей строке (где символов будет на один больше)
        current_line++;
    }

    return 0;
}