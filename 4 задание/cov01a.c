#include <stdio.h>

// Создаем константу для коэффициента (1 кг = 1000 г)
#define KOEF 1000

int main() {
    int total_grams; // Переменная для ввода общей массы в граммах
    int kg;          // Переменная для килограммов
    int g;           // Переменная для оставшихся граммов

    printf("---Mass converter---\n");
    printf("mass:\n");

    // Цикл работает, пока успешно считывается число И оно строго больше нуля
    while (scanf("%d", &total_grams) == 1 && total_grams > 0) {
        
        /* 
         * ОБЪЯСНЕНИЕ ОТБРАСЫВАНИЯ ДРОБНОЙ ЧАСТИ:
         * В языке C, когда мы делим целое число на целое число (например, total_grams / KOEF), 
         * результат всегда получается целым. Дробная часть просто отбрасывается (усекается в сторону нуля). 
         * Это происходит потому, что тип данных int не умеет хранить знаки после запятой, 
         * а процессор при обычной операции деления целых чисел выделяет под результат 
         * только целую часть. Чтобы узнать остаток, нужно использовать отдельный оператор — %.
         */
        kg = total_grams / KOEF; // Находим сколько полных килограммов в этой массе
        g = total_grams % KOEF;  // Находим остаток граммов, который не поместился в килограммы

        // Выводим результат на экран
        printf("Result: %d кг %d г\n\n", kg, g);

        printf("Enter the weight in grams: ");
    }

    printf("end.\n");
    return 0;
}